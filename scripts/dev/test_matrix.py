"""Run the complete test matrix file by file (P39.9 / P41.8) and write a JSON + Markdown summary.

Every test file runs in its own pytest process (bounded memory, a crash in one file cannot hide the others).
Live tests (``-m live``, BLOCKER-001) are deselected by the default addopts and reported as such.

Usage:
    .venv/bin/python scripts/dev/test_matrix.py [--out docs/testing/test-matrix-results] [--timeout 1800] [--only PATTERN]
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
import time
from datetime import UTC, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SUITES = ("unit", "contract", "integration", "failure", "security", "e2e", "load")
_COUNT = re.compile(r"(\d+) (passed|failed|skipped|deselected|errors?|xfailed|xpassed)")


def discover(only: str | None) -> list[Path]:
    files: list[Path] = []
    for suite in SUITES:
        files += sorted((ROOT / "tests" / suite).glob("test_*.py"))
    return [f for f in files if not only or re.search(only, str(f.relative_to(ROOT)))]


def run_file(path: Path, timeout: float) -> dict[str, object]:
    rel = str(path.relative_to(ROOT))
    started = time.monotonic()
    try:
        proc = subprocess.run(
            [sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider", rel],
            cwd=ROOT,
            capture_output=True,
            text=True,
            timeout=timeout,
            check=False,
        )
        tail = (proc.stdout or "").strip().splitlines()[-1:] or [""]
        summary = tail[0]
        rc = proc.returncode
    except subprocess.TimeoutExpired:
        summary, rc = f"TIMEOUT after {timeout:.0f}s", -1
    counts = {k: 0 for k in ("passed", "failed", "skipped", "deselected", "errors")}
    for n, kind in _COUNT.findall(summary):
        key = "errors" if kind.startswith("error") else kind
        if key in counts:
            counts[key] += int(n)
    ok = rc in (0, 5) and counts["failed"] == 0 and counts["errors"] == 0  # 5 = nothing collected (e.g. all live)
    return {
        "file": rel,
        "suite": rel.split("/")[1],
        "ok": ok,
        "rc": rc,
        "summary": summary,
        "seconds": round(time.monotonic() - started, 1),
        **counts,
    }


def main() -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--out", default=str(ROOT / "docs" / "testing" / "test-matrix-results"))
    p.add_argument("--timeout", type=float, default=1800)
    p.add_argument("--only", default=None)
    ns = p.parse_args()
    results = []
    for f in discover(ns.only):
        r = run_file(f, ns.timeout)
        results.append(r)
        print(f"{'OK ' if r['ok'] else 'FAIL'} {r['file']}: {r['summary']} ({r['seconds']}s)", flush=True)
    totals: dict[str, dict[str, int]] = {}
    for r in results:
        t = totals.setdefault(str(r["suite"]), {"files": 0, "passed": 0, "failed": 0, "skipped": 0, "deselected": 0, "errors": 0})
        t["files"] += 1
        for k in ("passed", "failed", "skipped", "deselected", "errors"):
            t[k] += int(r[k])  # type: ignore[call-overload]
    report = {"generated_at": datetime.now(UTC).isoformat(), "python": sys.version.split()[0], "totals": totals, "files": results}
    out = Path(ns.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.with_suffix(".json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    lines = [
        f"# Test matrix results ({report['generated_at'][:16]} UTC)",
        "",
        "Generated by `scripts/dev/test_matrix.py` (one pytest process per file; live tests deselected, BLOCKER-001).",
        "",
        "| Suite | Files | Passed | Failed | Errors | Skipped | Deselected (live) |",
        "|---|---|---|---|---|---|---|",
    ]
    for suite, t in totals.items():
        lines.append(f"| {suite} | {t['files']} | {t['passed']} | {t['failed']} | {t['errors']} | {t['skipped']} | {t['deselected']} |")
    all_t = {k: sum(t[k] for t in totals.values()) for k in ("files", "passed", "failed", "errors", "skipped", "deselected")}
    a = all_t
    lines.append(
        f"| **total** | **{a['files']}** | **{a['passed']}** | **{a['failed']}** | **{a['errors']}** | {a['skipped']} | {a['deselected']} |"
    )
    failing = [r for r in results if not r["ok"]]
    lines += ["", f"Failing files: {len(failing)}"] + [f"- `{r['file']}`: {r['summary']}" for r in failing]
    out.with_suffix(".md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return 0 if not failing else 1


if __name__ == "__main__":
    raise SystemExit(main())
